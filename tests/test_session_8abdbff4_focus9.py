def test_card_hashes_match_files_on_disk():
    card = _load(CARD)
    for rel, digest in card["evidence_sha256"].items():
        if rel == "docs/focus9-submission-guide.html":
            continue  # regenerated by the renderer; checked by the --check test below
        assert _sha(ROOT / rel) == digest, rel


def test_page_matches_generator_output():
    spec = importlib.util.spec_from_file_location(
        "render_focus9", ROOT / "scripts/render_focus9_submission_guide.py")
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    assert PAGE.read_text() == mod.render()


