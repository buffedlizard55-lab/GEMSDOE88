"""Session 8abdbff4 (2026-10-30): nine-site guide, official-spec review, negative run card.

These tests pin the research decision, not a score. No file is cleared.
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUDIT = ROOT / "evidence/focus9_nine_site_audit_20261030.json"
BLOBS = ROOT / "evidence/focus9_remote_blob_check_20261030.json"
LEADER = ROOT / "evidence/drivendata_leaderboard_snapshot_20261030.json"
CARD = ROOT / "registry/session_8abdbff4_run_card.json"
PAGE = ROOT / "docs/focus9-submission-guide.html"


def _load(path: Path):
    return json.loads(path.read_text())


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _claims(audit):
    return [c for c in audit["claims"] if "raster" in c]


def test_negative_decision_is_preserved():
    card = _load(CARD)
    audit = _load(AUDIT)
    assert card["decision"] == "DUPLICATE_STOP"
    assert card["verdict"] == "negative"
    assert card["submit"] == "NO"
    assert card["ok_to_submit"] is False
    assert card["ok_to_download_for_submission"] is False
    assert card["new_rasters_generated"] == 0
    assert card["weekly_slots_used"] == 0
    assert card["experiments_run"] == 0
    assert card["holdout"]["dti"] is None
    assert audit["ok_to_submit"] is False
    assert audit["new_rasters_generated"] == 0
    assert audit["weekly_slots_used"] == 0
    assert audit["experiments_run"] == 0


def test_audit_covers_all_21_claims_and_labels_scores_as_user_reported():
    audit = _load(AUDIT)
    claims = _claims(audit)
    assert len(claims) == 21
    assert {c["site"] for c in claims} == {
        "GEMSDOE24", "GEMSDOE25", "GEMSDOE27", "GEMSDOE28", "GEMSDOE30",
        "GEMSDOE31", "GEMSDOE32", "GEMSDOE33", "GEMSDOE36"}
    assert all(c["exists_at_pinned_head"] for c in claims)
    card = _load(CARD)
    assert card["claim_labels"]["per_claim"] == "USER-REPORTED CLAIM"
    assert card["claim_labels"]["organizer_receipts_found"] == 0
    assert card["claim_labels"]["holdout_dti_measured"] == 0


def test_literal_uniqueness_and_dense_witness_block():
    claims = _claims(_load(AUDIT))
    unique = [c for c in claims if c["unique_vs_nine_sites_literal"]]
    assert len(unique) == 2
    assert all(c["claimed_score"] < 0.1 for c in unique)
    assert all(c["dense_witness_blocks_candidate"] is True for c in claims)
    assert all(c["eligible_to_download_for_submission"] is False for c in claims)
    # Every top-scoring file per site is a literal duplicate.
    for site in {c["site"] for c in claims}:
        top = max((c for c in claims if c["site"] == site), key=lambda c: c["claimed_score"])
        assert top["unique_vs_nine_sites_literal"] is False, site


def test_official_spec_checks_pass_and_nan_outside_is_allowed():
    claims = _claims(_load(AUDIT))
    for c in claims:
        checks = c["official_spec_checks"]
        assert checks["float32"] and checks["single_layer"]
        assert checks["crs_EPSG_32611"] and checks["same_shape_as_grid"]
        assert checks["same_transform_as_grid"]
        assert checks["values_in_0_1_where_finite"]
        assert checks["no_nan_inside_study_footprint"]
        assert checks["nan_outside_footprint_allowed_by_spec"] is True
        assert c["official_spec_pass"] is True


