def norm01(a: np.ndarray, mask: np.ndarray) -> np.ndarray:
    vals = a[mask & np.isfinite(a)]
    if vals.size == 0:
        return np.zeros_like(a)
    lo, hi = np.percentile(vals, [5, 95])
    if hi <= lo:
        return np.zeros_like(a)
    out = np.clip((a - lo) / (hi - lo), 0.0, 1.0)
    out[~mask] = 0.0
    return out


