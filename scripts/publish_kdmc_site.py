def e(x) -> str:
    return html.escape(str(x), quote=True)


def fnum(x, nd=5):
    return "—" if x is None else f"{float(x):.{nd}f}"


def load(path: Path):
    return json.loads(path.read_text()) if path.is_file() else None


def best_arm(exp, predicate=lambda a: True):
    arms = [a for a in exp["arms"] if predicate(a)]
    return max(arms, key=lambda a: a["pooled_dti"]) if arms else None


def arm_by_name(exp, name):
    for a in exp["arms"]:
        if a["arm"] == name:
            return a
    return None


