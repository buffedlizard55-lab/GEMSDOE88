#!/usr/bin/env python3
"""Publish the H88-SDTL decision: release card (v3), status.json, file audit, rendered pages.

Reads only machine evidence (registry/sdtl88_run_card.json). Never edits the
verdict. Exits nonzero if any input is missing or inconsistent.
"""
from __future__ import annotations

if __name__ == "__main__":
    import sys as _guard_sys
    from pathlib import Path as _GuardPath
    _guard_sys.path.insert(0, str(_GuardPath(__file__).resolve().parents[1]))
    from scripts.generation_guard import enforce_generation_preflight
    enforce_generation_preflight()

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    # Direct API invocation must not republish the withdrawn clearance either.
    from scripts.generation_guard import enforce_generation_preflight
    enforce_generation_preflight(ROOT)
    card = json.loads((ROOT / "registry/sdtl88_run_card.json").read_text())
    if card.get("schema") != "gems88.run_card.v2":
        raise ValueError("unexpected run card schema")
    (ROOT / "docs/data/sdtl88_run_card.json").write_text(json.dumps(card, indent=2, allow_nan=False) + "\n")
    promote = card["verdict"] == "promote" and card["ok_to_submit"] is True
    r = card["raster"]
    h = card["holdout_dti"]
    sys.path.insert(0, str(ROOT))
    from scripts.validate_current import release_report
    release = release_report(ROOT)
    (ROOT / "docs/data/current_release.json").write_text(json.dumps(release, indent=2, allow_nan=False) + "\n")
    # status.json is owned by scripts/readiness.py (derived from the card + byte check).
    sys.path.insert(0, str(ROOT))
    from scripts import readiness
    status = readiness.current_status(ROOT)
    (ROOT / "docs/status.json").write_text(json.dumps(status, indent=2, allow_nan=False) + "\n")
    # Static head/strip text outside the canonical block must agree with the verdict.
    import re
    strip = ("H88-SDTL · NEW UNIQUE TIFF · OK TO DOWNLOAD AND SUBMIT" if promote
             else "H88-SDTL · NEW UNIQUE TIFF · RESEARCH DOWNLOAD ONLY · DO NOT SUBMIT")
    title_tag = "OK TO SUBMIT" if promote else "DO NOT SUBMIT"
    desc = ("New unique H88-SDTL competition TIFF, cleared by holdout, leakage, uniqueness and format gates. Download and submit."
            if promote else
            "New unique H88-SDTL research TIFF; not cleared for submission. Automated gates, evidence and limitations.")
    for name, title in (("index.html", "Overview"), ("executive-summary.html", "Submission guide")):
        path = ROOT / "docs" / name
        text = path.read_text()
        text = re.sub(r"<title>[^<]*</title>", f"<title>{title} · GEMSDOE88 · {title_tag}</title>", text, count=1)
        text = re.sub(r'name="description" content="[^"]*"', f'name="description" content="{desc}"', text, count=1)
        text = re.sub(r"<span data-card-status>[^<]*</span>", f"<span data-card-status>{strip}</span>", text, count=1)
        path.write_text(text, encoding="utf-8")
    # README decision block (between markers), rendered from the card only.
    h = card["holdout_dti"]; cand = h["candidate"]; ctrl = h["control_phys44"]; d = h["paired_delta_vs_control"]
    u = card["correlation_overlap_vs_registry"]; v = card["validator"]; can = card["leakage_canary"]
    far = h["far_gt10px"]
    head = ("## Download: YES · Submit: YES — OK TO DOWNLOAD AND SUBMIT" if promote
            else "## Download for research: YES · Submit: NO — DO NOT SUBMIT")
    gate = lambda ok: "PASS" if ok else "FAIL"
    readme_block = f"""<!-- SDTL88-DECISION:START -->
{head}

**Lane `H88-SDTL` (session SDTL-88, {card['generated_utc'][:10]}).** A new, protocol-unique TIFF was generated by `scripts/build_sdtl88_submission.py` from the preregistered slip/dilation-tendency lineament lane. Verdict **`{card['verdict']}`** is computed by code from four gates; no human edited it.

[**Download the TIFF**]({r['file']}) · [One-TIFF ZIP]({r['zip_file']}) · [Submission guide](docs/executive-summary.html) · [Run card (JSON)](registry/sdtl88_run_card.json)

- **Submission name:** `{card['submission_name']}`
- **Note ({card['note_chars']}/140):** `{card['submission_note']}`
- **TIFF SHA-256:** `{r['sha256']}` · ZIP SHA-256 `{r['zip_sha256']}` · {r['n_dots']:,} dots at 1.0, all other cells 0.0.

| Gate | Result | Evidence |
|---|---|---|
| Holdout rule (delta>0, CI low>0, ≥5/{str(h['folds_won_vs_control']).split('/')[-1]} folds) | **{gate(h['success'])}** | HOLDOUT-DTI (`{h['evaluator_version']}`, {cand['withheld_positive_pixels']:,} withheld positives): candidate {cand['dti']:.6f} [{cand['ci95'][0]:.6f}, {cand['ci95'][1]:.6f}] vs PHYS-44 control {ctrl['dti']:.6f}; paired delta {d['delta']:+.6f} [{d['ci95'][0]:+.6f}, {d['ci95'][1]:+.6f}]; folds won {h['folds_won_vs_control']}; far>10 px subset {far['candidate_sdtl']['dti']:.6f} vs {far['control_phys44']['dti']:.6f} |
| Leakage canary (max single-feature symmetric AUC ≤ 0.90) | **{gate(can['passed'])}** | {can['max_symmetric_auc']:.4f} over {can['features_tested']} features |
| Uniqueness v5 vs {u['rasters_checked']} local registry rasters (IR-88-SDTL-01) | **{gate(u['surface_ok'] and u['dots_ok'])}** | surface worst \\|ρ\\| {u['surface_worst_abs_spearman']:.4f} (limit 0.90); dots worst equal-support 3 px overlap {u['dots_worst_equal_support_overlap']:.4f} (limit 0.70); dots worst \\|ρ\\| {u['dots_worst_abs_spearman']:.4f} |
| Format validator (shared `validate_artifact`) | **{gate(v['ok'])}** | no NaN in footprint {v['no_nan_inside_footprint']}; values in [0,1] {v['values_in_0_1']}; CRS/shape/transform match {v['crs_match']}/{v['shape_match']}/{v['transform_match']}; no mass outside {v['no_mass_outside']} |

No ORGANIZER-CONFIRMED score exists for this file; the holdout instrument's known bias is recorded in `IRREGULARITIES.md` (IR-88-125, IR-88-SDTL-02). Weekly slot choice is the owner's; this repository picks none.
<!-- SDTL88-DECISION:END -->"""
    import re as _re
    readme = (ROOT / "README.md").read_text()
    readme = _re.sub(r"<!-- SDTL88-DECISION:START -->.*?<!-- SDTL88-DECISION:END -->", lambda _m: readme_block, readme, count=1, flags=_re.S)
    (ROOT / "README.md").write_text(readme, encoding="utf-8")
    # Pages copy of the session research note (linked from the rendered overview).
    (ROOT / "docs/research").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs/research/session-sdtl88-20261025.md").write_bytes((ROOT / "research/session-sdtl88-20261025.md").read_bytes())
    for cmd in (["scripts/audit_downloads.py"], ["scripts/render_decision.py"],
                ["scripts/audit_downloads.py", "--check"], ["scripts/render_decision.py", "--check"]):
        res = subprocess.run([sys.executable, *cmd], cwd=ROOT, text=True, capture_output=True)
        print(f"$ {' '.join(cmd)} -> exit {res.returncode}\n{res.stdout[-600:]}{res.stderr[-600:]}")
        if res.returncode != 0:
            return res.returncode
    print(f"PUBLISHED verdict={card['verdict']} ok_to_submit={promote} file={r['file']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
